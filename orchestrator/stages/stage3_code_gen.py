"""
Stage 3 — Iterative Code Generation.

Prompts the LLM to generate source code changes that make the locked
test suite pass.  The loop runs up to ``MAX_CODE_ITERATIONS`` times,
verifying test results and tamper-checking locked files after each
iteration.

If the locked tests are tampered with, the loop halts immediately and
triggers the escalation path.  If iterations are exhausted without all
tests passing, the escalation path is also triggered.

Implements FR-9, FR-10, FR-11.
"""

from __future__ import annotations

import logging
import time as _time
from typing import Any

from orchestrator.audit import AuditLogger
from orchestrator.checkpoint import Checkpoint
from orchestrator.ci_log_parser import format_errors_for_prompt, parse_ci_log
from orchestrator.ci_poller import CIResult, trigger_ci, wait_for_pipeline
from orchestrator.diff_patcher import apply_patches_to_sources, parse_llm_response
from orchestrator.llm_client import LLMClient
from orchestrator.notifier import (
    build_escalation_message,
    notify_email,
    notify_slack,
)
from orchestrator.preflight_checker import build_repair_prompt, check_all
from orchestrator.stages.stage1_context import TicketContext
from orchestrator.tamper_check import check_tampering

logger = logging.getLogger(__name__)

# Maximum sub-attempts per iteration when the LLM tries to modify locked files.
_MAX_LOCKED_REJECTIONS = 3


def run(
    context: TicketContext,
    gitlab: Any,
    llm: LLMClient,
    jira: Any,
    checkpoint: Checkpoint,
    audit: AuditLogger,
    *,
    max_iterations: int = 6,
    ci_poll_interval: int = 30,
    ci_timeout_minutes: int = 30,
    slack_webhook_url: str = "",
    escalation_email: str = "",
    reviewer_feedback: list[str] | None = None,
) -> dict[str, Any]:
    """
    Execute Stage 3: iterative code generation with tamper-checking.

    Returns
    -------
    dict[str, Any]
        Final test results from the last successful iteration.
    """
    audit.log(stage=3, event_type="stage3_start")
    ticket = context.ticket

    # ── Setup branch ────────────────────────────────────────────────
    logger.info("Setting up code branch…")
    code_branch = f"automation/{ticket.ticket_id}/code"
    tests_branch = f"automation/{ticket.ticket_id}/tests"
    ref_branch = tests_branch if gitlab.branch_exists(tests_branch) else context.default_branch
    if not gitlab.branch_exists(code_branch):
        gitlab.create_branch(code_branch, ref=ref_branch)
    checkpoint.code_branch = code_branch

    # Open draft PR/MR on first iteration (or reuse from checkpoint).
    if checkpoint.draft_mr_iid is None:
        logger.info("Creating draft PR for code generation…")
        mr_info = gitlab.create_mr(
            source_branch=code_branch,
            target_branch=context.default_branch,
            title=f"[Automated] {ticket.ticket_id}: {ticket.summary}",
            description=(
                f"## Automated Code Generation\n\n"
                f"**Ticket:** {ticket.ticket_id} — {ticket.summary}\n\n"
                f"Code generated by the spec-driven pipeline to pass the "
                f"locked test suite approved in Gate 1.\n\n"
                f"---\n"
                f"*This PR is updated after each coding iteration.*"
            ),
            draft=True,
        )
        checkpoint.draft_mr_iid = mr_info.iid
        audit.log(
            stage=3,
            event_type="draft_mr_created",
            payload={"mr_iid": mr_info.iid, "branch": code_branch},
        )

    # Collect locked test paths and CI workflow path for commit blocking.
    locked_paths = set(checkpoint.locked_test_hashes.keys())
    blocked_paths = set(locked_paths)
    ci_path = getattr(checkpoint, "ci_workflow_path", "")
    if ci_path:
        blocked_paths.add(ci_path)

    # Ensure context.test_files contains the locked tests from tests_branch
    if locked_paths:
        locked_test_contents = _fetch_locked_test_contents(
            gitlab, checkpoint.tests_branch or code_branch, locked_paths
        )
        context.test_files.update(locked_test_contents)

    # Build initial source snapshot from context.
    current_sources: dict[str, str] = dict(context.source_files)
    last_test_output = ""
    start_iteration = checkpoint.iteration_count + 1

    # ── Coding loop ─────────────────────────────────────────────────────
    for iteration in range(start_iteration, max_iterations + 1):
        checkpoint.iteration_count = iteration
        logger.info(
            "▸ Iteration %d/%d for %s",
            iteration, max_iterations, ticket.ticket_id,
        )
        audit.log(
            stage=3,
            event_type="iteration_start",
            payload={"iteration": iteration},
        )

        # ── 1. Prompt the LLM ────────────────────────────────────────
        active_reviewer_feedback = reviewer_feedback or getattr(checkpoint, "reviewer_feedback", [])

        # N1 fix: Reset LLM history before every coding iteration so the model
        # cannot use stale in-context memory of files modified by prior iterations.
        # Each iteration's prompt already injects the CURRENT file content via
        # `current_sources` (re-fetched from Git HEAD after the previous commit).
        # If history is kept, the model hallucinates SEARCH blocks that matched
        # the file on iteration 1 but no longer exist after iteration 2+ patched it.
        if iteration > 1:
            logger.info(
                "Clearing LLM history before iteration %d to prevent SEARCH text drift "
                "(stale in-context memory of prior file content).",
                iteration,
            )
            llm.clear_history(keep_system=True)

        logger.info("LLM call: generating code changes…")
        t0 = _time.monotonic()
        generated_files = _generate_code(
            llm=llm,
            context=context,
            current_sources=current_sources,
            last_test_output=last_test_output,
            iteration=iteration,
            blocked_paths=blocked_paths,
            reviewer_feedback=active_reviewer_feedback,
        )
        elapsed = _time.monotonic() - t0
        logger.info("LLM responded in %.1fs with %d file(s)", elapsed, len(generated_files) if generated_files else 0)

        if not generated_files:
            logger.warning("LLM returned no file changes in iteration %d", iteration)
            audit.log(
                stage=3,
                event_type="iteration_result",
                payload={"iteration": iteration, "result": "no_changes"},
            )
            continue

        # ── 2. Pre-flight syntax verification (Phase 3) ─────────────
        logger.info("Running local pre-flight syntax verification…")
        preflight_passed, preflight_results = check_all(generated_files)
        if not preflight_passed:
            failed_paths = [r.path for r in preflight_results if not r.passed]
            logger.warning(
                "Pre-flight FAILED for %d file(s): %s — skipping remote commit, re-prompting LLM.",
                len(failed_paths), failed_paths,
            )
            audit.log(
                stage=3,
                event_type="preflight_failed",
                payload={"iteration": iteration, "failed_files": failed_paths},
            )
            repair_prompt = build_repair_prompt(preflight_results)
            response = llm.chat(
                repair_prompt,
                stage=3,
                call_purpose=f"Syntax repair for iteration {iteration}",
                attached_files=list(generated_files.keys()),
            )
            repair_content = response.get("content", "")
            repaired_parsed = parse_llm_response(repair_content)
            repaired_files, _, _ = apply_patches_to_sources(repaired_parsed, current_sources)
            if repaired_files:
                generated_files = repaired_files
                logger.info("Repair produced %d file(s); proceeding with commit.", len(generated_files))
            else:
                logger.warning("LLM repair returned no files; skipping iteration %d.", iteration)
                continue

        # ── 3. Commit changes ────────────────────────────────────────
        logger.info("Committing %d file(s) to branch %s", len(generated_files), code_branch)
        commit_sha = gitlab.commit_files(
            branch=code_branch,
            files=generated_files,
            commit_message=(
                f"[spec-driven] Iteration {iteration} for "
                f"{ticket.ticket_id}"
            ),
            blocked_paths=blocked_paths,
        )
        logger.info("Commit successful")

        # ── 4. Re-fetch modified files from Git HEAD (Fix Issue 1) ───
        # Ensures current_sources always reflects what is actually on
        # the branch, not a potentially stale in-memory dict.
        for path in generated_files:
            try:
                fresh = gitlab.get_file_content(path, ref=code_branch)
                current_sources[path] = fresh
            except Exception:
                # File too new to show yet; keep local patched content.
                current_sources[path] = generated_files[path]
        checkpoint.modified_files = list(
            set(checkpoint.modified_files) | set(generated_files.keys())
        )

        # ── 3. Trigger CI/CD (test-only run) ─────────────────────────
        logger.info("Triggering CI test run…")
        pipeline_id = trigger_ci(
            gitlab,
            code_branch,
            variables={"TEST_ONLY": "true"},
            commit_sha=commit_sha,
        )
        checkpoint.ci_pipeline_id = pipeline_id
        checkpoint.save(checkpoint_dir=_infer_checkpoint_dir(checkpoint))

        ci_result: CIResult = wait_for_pipeline(
            gitlab, pipeline_id,
            poll_interval_seconds=ci_poll_interval,
            timeout_minutes=ci_timeout_minutes,
        )

        # ── 4. Tamper-check locked test files ──────────────────────
        logger.info("Verifying locked test file integrity…")
        current_test_contents = _fetch_locked_test_contents(
            gitlab, code_branch, locked_paths,
        )
        tampered = check_tampering(
            checkpoint.locked_test_hashes, current_test_contents,
        )
        if tampered:
            logger.error(
                "TAMPER DETECTED in iteration %d: %s", iteration, tampered,
            )
            audit.log(
                stage=3,
                event_type="tamper_detected",
                payload={"iteration": iteration, "tampered_files": tampered},
            )
            _handle_escalation(
                ticket_id=ticket.ticket_id,
                jira=jira,
                iterations=iteration,
                test_results={"passed": 0, "failed": 0, "tampered": tampered},
                blocker="Test file tampering detected",
                mr_url=f"MR !{checkpoint.draft_mr_iid}",
                slack_webhook_url=slack_webhook_url,
                escalation_email=escalation_email,
                gitlab=gitlab,
                mr_iid=checkpoint.draft_mr_iid,
                audit=audit,
            )
            raise RuntimeError(
                f"Tamper detected in iteration {iteration}: {tampered}"
            )

        # ── 5. Parse test results ──────────────────────────────────────
        test_results = _parse_ci_test_results(ci_result)
        checkpoint.last_test_results = test_results
        last_test_output = _format_test_output(ci_result, test_results, gitlab=gitlab)

        audit.log(
            stage=3,
            event_type="iteration_result",
            payload={
                "iteration": iteration,
                "ci_status": ci_result.status,
                "test_results": test_results,
            },
        )
        checkpoint.save(checkpoint_dir=_infer_checkpoint_dir(checkpoint))

        # ── 6. Check if all tests pass ─────────────────────────────────
        if ci_result.passed and test_results.get("failed", 0) == 0:
            logger.info(
                "✓ All target tests pass after iteration %d", iteration,
            )
            audit.log(
                stage=3,
                event_type="stage3_complete",
                payload={"iterations_used": iteration, "test_results": test_results},
            )
            checkpoint.current_stage = 4
            return test_results

    # ── Exhausted all iterations — escalation ──────────────────────────
    logger.warning(
        "Exhausted %d iterations for %s — escalating.",
        max_iterations, ticket.ticket_id,
    )
    blocker = _get_blocker_assessment(llm, last_test_output)
    _handle_escalation(
        ticket_id=ticket.ticket_id,
        jira=jira,
        iterations=max_iterations,
        test_results=checkpoint.last_test_results,
        blocker=blocker,
        mr_url=f"MR !{checkpoint.draft_mr_iid}",
        slack_webhook_url=slack_webhook_url,
        escalation_email=escalation_email,
        gitlab=gitlab,
        mr_iid=checkpoint.draft_mr_iid,
        audit=audit,
    )
    raise RuntimeError(
        f"Stage 3 exhausted {max_iterations} iterations for {ticket.ticket_id}"
    )


# ── LLM prompt helpers ──────────────────────────────────────────────────


def _lang_for_path(path: str) -> str:
    ext = path.rsplit(".", 1)[-1].lower() if "." in path else ""
    return {
        "py": "python",
        "js": "javascript",
        "ts": "typescript",
        "tsx": "tsx",
        "jsx": "jsx",
        "java": "java",
        "go": "go",
        "rs": "rust",
        "html": "html",
        "css": "css",
        "json": "json",
        "yml": "yaml",
        "yaml": "yaml",
    }.get(ext, "")


def _generate_code(
    llm: LLMClient,
    context: TicketContext,
    current_sources: dict[str, str],
    last_test_output: str,
    iteration: int,
    blocked_paths: set[str] | None = None,
    locked_paths: set[str] | None = None,
    reviewer_feedback: list[str] | None = None,
) -> dict[str, str]:
    """
    Prompt the LLM to generate code changes and parse the response.

    If the LLM tries to modify locked test files or CI workflows, it is re-prompted
    up to ``_MAX_LOCKED_REJECTIONS`` times.
    """
    effective_blocked = set(blocked_paths or ()) | set(locked_paths or ())
    ticket = context.ticket

    # Build source context.
    source_summary = "\n".join(
        f"### `{path}`\n```{_lang_for_path(path)}\n{content}\n```"
        for path, content in list(current_sources.items())[:15]
    )

    # Build locked test context (read-only).
    locked_tests_summary = ""
    if context.test_files:
        locked_tests_summary = "## Locked Test Files (DO NOT MODIFY)\n" + "\n".join(
            f"### `{path}`\n```{_lang_for_path(path)}\n{content}\n```"
            for path, content in list(context.test_files.items())[:10]
        )

    # Human Approver Review Feedback (Gate 2 loop)
    feedback_section = ""
    if reviewer_feedback:
        fb_list = "\n".join(f"- {c}" for c in reviewer_feedback)
        feedback_section = (
            "## 🚨 PRIMARY OBJECTIVE: Human Approver Review Feedback\n"
            "A human reviewer has reviewed the previous Pull Request and explicitly requested the following improvements.\n"
            "Satisfying ALL points below is your PRIMARY target. Making tests pass is secondary:\n"
            f"{fb_list}\n\n"
        )

    task_desc = (
        "Your PRIMARY task is to address ALL points raised in the Human Approver's review feedback. "
        "Satisfying these reviewer comments is GOAL 1. Maintaining locked test pass status is GOAL 2 (secondary)."
        if reviewer_feedback
        else "Your task is to implement clean, targeted, surgical code changes that satisfy the ticket's "
        "acceptance criteria and make the locked test suite pass."
    )

    # Issue 2 fix: structured error extraction replaces raw log dump.
    # The LLM now receives precise file:line:message diagnostics instead
    # of a 100-line CI blob it has to mentally parse.
    iteration_context = ""
    if last_test_output and iteration > 1:
        parsed_errors = parse_ci_log(last_test_output)
        if parsed_errors:
            structured = format_errors_for_prompt(parsed_errors)
            iteration_context = (
                f"{structured}\n\n"
                f"Address EVERY error listed above. Do not make changes to unrelated code.\n\n"
            )
        else:
            # Fallback: short raw tail if parser found nothing actionable
            test_lines = last_test_output.strip().splitlines()
            tail = "\n".join(test_lines[-40:])
            iteration_context = (
                f"## Previous Iteration Failure (raw tail)\n"
                f"```\n{tail}\n```\n\n"
                f"Analyse the failure and fix the root cause.\n\n"
            )

    has_react = any("react" in p.lower() or p.endswith((".tsx", ".jsx")) for p in context.all_file_paths)
    react_hint = (
        "6. In React components, ensure hooks that require external providers (such as useNavigate from react-router) "
        "are safely handled with a fallback so components can be rendered in isolated unit tests.\n"
        if has_react
        else ""
    )

    prompt = (
        "You are a senior software engineer acting as a surgical AI coding agent. "
        f"{task_desc}\n\n"
        "## Ticket\n"
        f"**ID:** {ticket.ticket_id}\n"
        f"**Summary:** {ticket.summary}\n"
        f"**Description:**\n{ticket.description}\n\n"
        f"**Acceptance Criteria:**\n{ticket.acceptance_criteria}\n\n"
        f"{feedback_section}"
        f"{iteration_context}"
        f"## Current Source Files\n{source_summary}\n\n"
        f"{locked_tests_summary}\n\n"
        "## Critical Rules\n"
        "1. SURGICAL EDITS ONLY: Identify the exact lines, rules, or functions that need changing. "
        "DO NOT rewrite entire files. DO NOT regenerate unchanged code. Keep the blast radius minimal.\n"
        "2. PRESERVE EXISTING ARCHITECTURE: You MUST preserve ALL existing layout structures "
        "(flex/grid splits, column widths, fixed sizes, sticky positioning, responsive breakpoints) "
        "and all unrelated components. Do NOT remove or alter working properties.\n"
        "3. IMMUTABLE FILES: You MUST NOT modify any locked test files or CI workflow files.\n"
        "4. PRIMARY OBJECTIVE: Satisfy ALL human reviewer comments and acceptance criteria first. "
        "Locked tests passing is secondary.\n"
        "5. ONLY EMIT CHANGED FILES: Only include files that actually need modifications.\n"
        f"{react_hint}\n"
        "## Mandatory Two-Stage Response Format\n"
        "Your response MUST have exactly two sections:\n\n"
        "### 1. ARCHITECTURAL PLAN & IMPACT ANALYSIS\n"
        "Before writing any code, write your plan here. Include:\n"
        "- **Identified Change Locations:** Which file(s) and which specific lines/selectors/functions to edit\n"
        "- **Preservation Verification:** Explicit confirmation that flex/grid layouts, sticky positioning, "
        "column widths, and all unrelated DOM/CSS sections are left untouched\n"
        "- **Reviewer Feedback Addressed:** List each reviewer comment and how you will address it\n\n"
        "### 2. CODE EDITS\n"
        "After the plan, emit ONLY the changed code sections using SEARCH/REPLACE blocks:\n"
        "```\n"
        "// FILE: path/to/file.ext\n"
        "<<<<<<< SEARCH\n"
        "[exact original lines to find -- must be unique in the file]\n"
        "=======\n"
        "[replacement lines]\n"
        ">>>>>>> REPLACE\n"
        "```\n"
        "- Each SEARCH block must match EXACTLY what is in the file (whitespace included).\n"
        "- For BRAND NEW files only, use: `// FILE: path` followed by the complete content "
        "(no SEARCH/REPLACE needed).\n"
        "- Do NOT output whole-file rewrites for existing files -- use SEARCH/REPLACE blocks only."
    )

    for attempt in range(1, _MAX_LOCKED_REJECTIONS + 1):
        response = llm.chat(
            prompt,
            stage=3,
            call_purpose=f"Code generation iteration {iteration} (attempt {attempt})",
            attached_files=list(current_sources.keys()),
        )
        raw_content = response.get("content", "")

        # ── Parse using the surgical diff patcher (Phase 1) ──────────
        parsed_patches = parse_llm_response(raw_content)
        if not parsed_patches:
            # Fallback: legacy full-file parser as last resort.
            # Issue 3 fix: warn visibly + re-prompt for format compliance.
            logger.warning(
                "LLM response for iteration %d contained no SEARCH/REPLACE blocks. "
                "Falling back to legacy full-file parser and re-prompting for format "
                "compliance on next attempt.",
                iteration,
            )
            audit.log(
                stage=3,
                event_type="format_noncompliant",
                payload={"iteration": iteration, "attempt": attempt},
            )
            files = _parse_generated_files(raw_content)
            # Re-prompt for format compliance on next attempt
            if attempt < _MAX_LOCKED_REJECTIONS:
                prompt = (
                    "Your previous response did not use the required SEARCH/REPLACE block format. "
                    "You MUST respond using SEARCH/REPLACE blocks only for existing files. "
                    "Do NOT output full file rewrites. Here is the required format:\n\n"
                    "// FILE: path/to/file.ext\n"
                    f"{chr(60)*7} SEARCH\n"
                    "[exact original lines to find]\n"
                    "=======\n"
                    "[replacement lines]\n"
                    f"{chr(62)*7} REPLACE\n\n"
                    "Resend your changes in this format now."
                )
                continue
        else:
            # Issue 4 fix: Extract and log the architectural plan before code edits.
            plan_section = _extract_plan_section(raw_content)
            if plan_section:
                logger.info(
                    "[Plan] Iteration %d architectural plan logged (%d chars): %.300s",
                    iteration, len(plan_section), plan_section,
                )

            # Issue 11 fix: all-or-nothing commit gate.
            files, patch_results, all_succeeded = apply_patches_to_sources(
                parsed_patches, current_sources
            )
            failed_patches = [pr for pr in patch_results if not pr.success]
            for pr in failed_patches:
                logger.warning("Patch failed for %s: %s", pr.path, pr.errors)

            if not all_succeeded and attempt < _MAX_LOCKED_REJECTIONS:
                # Build a targeted re-prompt from the failed patches.
                fail_details = "\n".join(
                    f"- FILE `{pr.path}`: {'; '.join(pr.errors[:2])}"
                    for pr in failed_patches
                )
                logger.warning(
                    "All-or-nothing gate: %d patch(es) failed — aborting commit, "
                    "re-prompting LLM (attempt %d/%d).\n%s",
                    len(failed_patches), attempt, _MAX_LOCKED_REJECTIONS, fail_details,
                )
                prompt = (
                    f"Your SEARCH/REPLACE blocks contained {len(failed_patches)} "
                    f"failure(s) that could not be applied:\n\n{fail_details}\n\n"
                    "These failures are likely because the SEARCH text does not exactly "
                    "match the current file content (whitespace, surrounding context, "
                    "or already-applied changes). Please:\n"
                    "1. Include MORE surrounding lines in your SEARCH block to make it unique.\n"
                    "2. Make sure the SEARCH text exactly matches the current file content.\n"
                    "3. Resubmit ONLY the failed patches in corrected SEARCH/REPLACE format."
                )
                continue

        # Check for locked/blocked file violations.
        violations = set(files.keys()) & effective_blocked
        if not violations:
            return files

        logger.warning(
            "LLM attempted to modify locked/blocked files (attempt %d/%d): %s",
            attempt, _MAX_LOCKED_REJECTIONS, violations,
        )
        # Remove violating files and re-prompt.
        for v in violations:
            del files[v]

        if attempt < _MAX_LOCKED_REJECTIONS:
            prompt = (
                f"Your previous response included modifications to immutable files "
                f"({', '.join(violations)}). These files must not be changed. "
                f"Please regenerate your SEARCH/REPLACE code changes WITHOUT modifying "
                f"any of these files. Only create or update implementation source files."
            )

    # Return whatever non-violating files we have.
    return files


def _parse_generated_files(llm_output: str) -> dict[str, str]:
    """
    Parse the LLM's response into ``{file_path: content}`` pairs.

    Supports:
      - ``// FILE: path``, ``# FILE: path``, ``/* FILE: path */``
      - ``// filepath: path``, ``// filename: path``
      - Markdown headers like ``### `path` ``
      - Both fenced (```) and unfenced code outputs
    """
    files: dict[str, str] = {}
    lines = llm_output.splitlines()
    current_path: str | None = None
    current_content: list[str] = []

    prefixes = ("// FILE:", "# FILE:", "/* FILE:", "// filepath:", "// filename:", "# filepath:", "# filename:")

    for line in lines:
        stripped = line.strip()

        # Check for file marker
        is_marker = False
        target_path = None

        for prefix in prefixes:
            if stripped.lower().startswith(prefix.lower()):
                raw = stripped[len(prefix):].removesuffix("*/").strip().strip("`'\"")
                # Issue 10 fix: terminate at first whitespace
                raw = raw.split()[0] if raw.split() else raw
                if raw:
                    is_marker = True
                    target_path = raw.replace("\\", "/")
                    break

        if not is_marker and (stripped.startswith("### `") or stripped.startswith("## `")) and stripped.endswith("`"):
            raw = stripped.lstrip("#").strip().strip("`'\"")
            if "." in raw:  # looks like a file path
                is_marker = True
                target_path = raw.replace("\\", "/")

        if is_marker and target_path:
            if current_path and current_content:
                files[current_path] = "\n".join(current_content).strip()
            current_path = target_path
            current_content = []
            continue

        if current_path is not None:
            # Skip code fence lines like ``` or ```typescript
            if stripped.startswith("```"):
                continue
            current_content.append(line)

    if current_path and current_content:
        files[current_path] = "\n".join(current_content).strip()

    return files


def _extract_plan_section(raw_response: str) -> str:
    """
    Issue 4 fix: Extract the ARCHITECTURAL PLAN section from the LLM's
    two-stage response so it can be logged to audit.

    Looks for text between the plan header and the CODE EDITS header.
    Returns an empty string if the section is not found.
    """
    import re as _re
    plan_start = _re.search(
        r"###?\s*1\.?\s*ARCHITECTURAL PLAN",
        raw_response, _re.IGNORECASE,
    )
    code_start = _re.search(
        r"###?\s*2\.?\s*CODE EDITS",
        raw_response, _re.IGNORECASE,
    )
    if plan_start:
        start_idx = plan_start.end()
        end_idx = code_start.start() if code_start else len(raw_response)
        return raw_response[start_idx:end_idx].strip()
    return ""


def _fetch_locked_test_contents(
    gitlab: Any,
    branch: str,
    locked_paths: set[str],
) -> dict[str, str]:
    """Fetch the current contents of locked test files from the branch."""
    contents: dict[str, str] = {}
    for path in locked_paths:
        try:
            contents[path] = gitlab.get_file_content(path, ref=branch)
        except Exception:
            # File missing — will be caught by tamper_check as deletion.
            logger.warning("Could not fetch locked file %s from branch %s", path, branch)
    return contents


def _parse_ci_test_results(ci_result: CIResult) -> dict[str, Any]:
    """
    Extract structured test results from the CI pipeline result.

    In the absence of parsed Jest JSON artifacts, we derive results
    from the pipeline and job statuses.
    """
    test_job_status = ci_result.job_status("test")
    is_passed = test_job_status in ("success", "passed") and ci_result.status in ("success", "passed")
    is_failed = test_job_status in ("failed", "failure") or ci_result.status in ("failed", "failure")

    return {
        "passed": 1 if is_passed else 0,
        "failed": 1 if is_failed else 0,
        "ci_status": ci_result.status,
        "test_job_status": test_job_status or "unknown",
        "details": f"Pipeline {ci_result.pipeline_id}: {ci_result.status}",
    }


def _format_test_output(
    ci_result: CIResult,
    test_results: dict[str, Any],
    gitlab: Any = None,
) -> str:
    """Format a human-readable summary of the test results, including live CI logs if tests failed."""
    lines = [
        f"Pipeline {ci_result.pipeline_id}: {ci_result.status}",
        f"Pipeline URL: {ci_result.web_url}",
        "",
        "Job Results:",
    ]
    test_job_id = None
    for job in ci_result.jobs:
        lines.append(f"  - {job.get('name', '?')}: {job.get('status', '?')}")
        if job.get("name") == "test":
            test_job_id = job.get("id")

    lines.append("")
    lines.append(
        f"Test Summary: passed={test_results.get('passed', 0)}, "
        f"failed={test_results.get('failed', 0)}"
    )

    # If test failed and gitlab client supports fetching job traces, include recent container logs
    has_failed = (
        test_results.get("failed", 0) > 0
        or ci_result.status in ("failed", "failure")
        or any(j.get("status") in ("failed", "failure") for j in ci_result.jobs)
    )
    if (
        has_failed
        and gitlab
        and test_job_id
        and hasattr(gitlab, "get_job_trace")
    ):
        try:
            trace = gitlab.get_job_trace(test_job_id)
            if trace:
                trace_lines = trace.strip().splitlines()
                # Include last 80 lines of the trace
                snippet = "\n".join(trace_lines[-80:])
                lines.append("\nTarget Test Failure Logs (from CI container):")
                lines.append(snippet)
        except Exception as exc:
            logger.debug("Could not fetch test job trace: %s", exc)

    return "\n".join(lines)


def _get_blocker_assessment(llm: LLMClient, last_test_output: str) -> str:
    """Ask the LLM to summarise why the tests are still failing."""
    prompt = (
        "The automated coding loop has exhausted all iterations and the "
        "target tests are still failing.  Based on the last test output "
        "below, provide a brief (2-3 sentence) assessment of what is "
        "blocking the fix.\n\n"
        f"```\n{last_test_output}\n```"
    )
    response = llm.chat(prompt)
    return response.get("content", "Unable to determine blocker.")


def _handle_escalation(
    ticket_id: str,
    jira: Any,
    iterations: int,
    test_results: dict[str, Any],
    blocker: str,
    mr_url: str,
    slack_webhook_url: str,
    escalation_email: str,
    gitlab: Any,
    mr_iid: int | None,
    audit: AuditLogger,
) -> None:
    """Execute the escalation path: label MR, JIRA comment, notify."""
    audit.log(
        stage=3,
        event_type="escalation_triggered",
        payload={
            "iterations": iterations,
            "test_results": test_results,
            "blocker": blocker,
        },
    )

    # Label the MR.
    if mr_iid:
        try:
            gitlab.add_mr_label(mr_iid, "partial-needs-human")
        except Exception as exc:
            logger.error("Failed to label MR !%d: %s", mr_iid, exc)

    # Build escalation message.
    message = build_escalation_message(
        ticket_id=ticket_id,
        iterations=iterations,
        test_results=test_results,
        blocker_assessment=blocker,
        mr_url=mr_url,
    )

    # Post JIRA comment.
    try:
        jira.post_comment(ticket_id, message)
    except Exception as exc:
        logger.error("Failed to post JIRA comment for %s: %s", ticket_id, exc)

    # Slack notification.
    notify_slack(slack_webhook_url, message)

    # Email notification.
    notify_email(
        to=escalation_email,
        subject=f"[Escalation] Automated resolution failed for {ticket_id}",
        body=message,
    )


