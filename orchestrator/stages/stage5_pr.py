"""
Stage 5 — Pull Request Promotion & Human Approval Gate 2.

Following successful Stage 4 CI validation, this stage:
  1. Promotes the draft PR opened in Stage 3 to ready-for-review.
  2. Updates the PR description with diff statistics, full test results,
     and the 5-gate CI validation table.
  3. Transitions the originating ticket to 'Under Review' and posts
     the PR link.
  4. Sends reviewer notifications via Slack and Email.
  5. Monitors Gate 2 human approval:
     - On approval: logs to audit, advances ticket state, and completes the pipeline.
     - On changes requested (FR-21): extracts reviewer feedback and returns
       status to route execution back to Stage 3.

Implements FR-17 through FR-21.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Any

from orchestrator.audit import AuditLogger
from orchestrator.checkpoint import Checkpoint
from orchestrator.gitlab_gate import GateOutcome, GateResult, wait_for_approval
from orchestrator.notifier import (
    notify_feedback_received,
    notify_gate2_approved,
    notify_gate2_pending,
    notify_pipeline_complete,
)
from orchestrator.stages.stage1_context import TicketContext
from orchestrator.stages.stage4_validation import ValidationResult

logger = logging.getLogger(__name__)


@dataclass
class Stage5Result:
    """Outcome of Stage 5 PR promotion and Gate 2 evaluation."""

    mr_iid: int
    mr_url: str
    status: str  # "approved", "changes_requested", "timeout"
    approved_by: list[str] = field(default_factory=list)
    reviewer_feedback: list[str] = field(default_factory=list)

    @property
    def approved(self) -> bool:
        return self.status == "approved"

    @property
    def changes_requested(self) -> bool:
        return self.status == "changes_requested"


def _build_mr_description(
    context: TicketContext,
    validation_result: ValidationResult,
    checkpoint: Checkpoint,
) -> str:
    """
    Format a rich, structured Markdown description for the ready-for-review PR/MR.
    """
    ticket = context.ticket
    modified_files_list = (
        "\n".join(f"- `{f}`" for f in checkpoint.modified_files)
        if checkpoint.modified_files
        else "- *(Modified files tracked in commit diff)*"
    )

    # Summarize test results from checkpoint
    test_res = checkpoint.last_test_results or {}
    passed = test_res.get("passed", 0)
    failed = test_res.get("failed", 0)
    total = passed + failed
    test_summary = f"{passed}/{total} passed" if total > 0 else "All target tests passed"

    # Build CI validation table
    gate_rows = []
    for g in validation_result.gates:
        status_icon = "✅ PASS" if g.passed else ("⚠️ SKIPPED" if g.status == "skipped" else "❌ FAIL")
        gate_rows.append(f"| `{g.name}` | {status_icon} | {g.status.capitalize()} |")

    gate_table = (
        "| Gate / Job | Result | Status |\n"
        "|---|---|---|\n"
        + "\n".join(gate_rows)
    )

    ticket_url = ticket.raw.get("html_url") or ticket.raw.get("self") or "#"

    return (
        f"## 🤖 Spec-Driven Automated PR: {ticket.ticket_id}\n\n"
        f"**Originating Ticket:** [{ticket.ticket_id}]({ticket_url}) — *Closes #{ticket.ticket_id}*\n\n"
        f"### 📋 Summary\n"
        f"{ticket.summary}\n\n"
        f"### 🎯 Acceptance Criteria Verified\n"
        f"```text\n{ticket.acceptance_criteria}\n```\n\n"
        f"### 🛠️ Changes Implemented (Iteration {checkpoint.iteration_count} of 6)\n"
        f"{modified_files_list}\n\n"
        f"### 🧪 Test Execution Results\n"
        f"- **Target Tests:** {test_summary}\n"
        f"- **Locked Tests Integrity:** Verified (all test hashes intact)\n\n"
        f"### 🛡️ CI/CD Quality Gate Results\n"
        f"[View CI Pipeline #{validation_result.pipeline_id}]({validation_result.pipeline_url})\n\n"
        f"{gate_table}\n\n"
        f"---\n"
        f"**Security & Governance:**\n"
        f"- Generated by Spec-Driven Automation Agent.\n"
        f"- Tests were pre-generated and approved at **Human Gate 1** prior to coding.\n"
        f"- Tamper detection verified zero alterations to approved test suites.\n"
        f"- All CI quality gates passed. Ready for human code review.\n\n"
        f"*(Human approval required to merge. Auto-merge is strictly disabled per FR-20.)*"
    )


def run(
    ticket_id: str,
    context: TicketContext,
    validation_result: ValidationResult,
    checkpoint: Checkpoint,
    audit: AuditLogger,
    gitlab: Any,
    jira: Any,
    *,
    gate_poll_interval: int = 30,
    gate_timeout_hours: float = 48.0,
    slack_webhook_url: str = "",
    escalation_email: str = "",
) -> Stage5Result:
    """
    Execute Stage 5: promote draft PR, sync ticket state, notify reviewers, and wait
    for Gate 2 approval or reviewer feedback.
    """
    audit.log(stage=5, event_type="stage5_start")
    mr_iid = checkpoint.draft_mr_iid
    if mr_iid is None:
        raise ValueError("Cannot run Stage 5: draft_mr_iid is not set in checkpoint.")

    # ── 1. Promote draft PR to ready-for-review ──────────────────────────
    logger.info("Promoting PR #%s to ready-for-review…", mr_iid)
    gitlab.promote_mr_to_ready(mr_iid)
    gitlab.add_mr_label(mr_iid, "ready-for-review")
    gitlab.add_mr_label(mr_iid, "spec-driven-dev")

    # ── 2. Update PR description with full report ────────────────────────
    logger.info("Updating PR description with validation report…")
    description = _build_mr_description(context, validation_result, checkpoint)
    gitlab.update_mr_description(mr_iid, description)
    audit.log(stage=5, event_type="stage5_mr_promoted", payload={"mr_iid": mr_iid})

    if hasattr(gitlab, "_project"):
        mr_url = f"{gitlab._project.web_url}/-/merge_requests/{mr_iid}"
    elif hasattr(gitlab, "_repo"):
        mr_url = f"{gitlab._repo.html_url}/pull/{mr_iid}"
    else:
        mr_url = f"https://github.com/pull/{mr_iid}"

    checkpoint.final_mr_url = mr_url
    checkpoint.gate2_mr_iid = mr_iid

    # ── 3. Ticket Synchronization ─────────────────────────────────────────
    logger.info("Synchronizing ticket status to review…")
    jira.transition_ticket(
        ticket_id,
        ["Under Review", "In Review", "Ready for Review", "In Progress"],
    )
    gates_summary = "\n".join(
        f"- {g.name}: {'PASS' if g.passed else g.status}" for g in validation_result.gates
    )
    jira.post_lifecycle_comment(
        ticket_id=ticket_id,
        title="Gate 2 — Ready for Review",
        message=(
            f"Code generation and all 5 CI validation gates completed successfully!\n\n"
            f"*Validation Summary:*\n{gates_summary}\n\n"
            f"Please review the PR diffs and approve."
        ),
        mr_url=mr_url,
    )

    # ── 4. Reviewer Notifications ────────────────────────────────────────
    notify_gate2_pending(
        slack_webhook_url=slack_webhook_url,
        escalation_email=escalation_email,
        ticket_id=ticket_id,
        mr_url=mr_url,
        gate_results_summary=gates_summary,
    )

    # ── 5. Gate 2 Human Approval Monitoring Loop ─────────────────────────
    logger.info("Waiting for Gate 2 Human Approval (PR #%s)…", mr_iid)
    seen_comments: set[str] = set()

    # Pre-seed seen_comments with any comments already present on the PR
    if hasattr(gitlab, "get_pr_notes"):
        for n in gitlab.get_pr_notes(mr_iid):
            b = (n.get("body") or "").strip()
            if b:
                seen_comments.add(b)
    elif hasattr(gitlab, "get_mr_notes"):
        for n in gitlab.get_mr_notes(mr_iid):
            b = (n.get("body") or "").strip()
            if b:
                seen_comments.add(b)

    gate_result: GateResult = wait_for_approval(
        gitlab=gitlab,
        mr_iid=mr_iid,
        poll_interval_seconds=gate_poll_interval,
        timeout_hours=gate_timeout_hours,
        return_on_changes_requested=True,
        seen_comments=seen_comments,
    )

    if gate_result.outcome == GateOutcome.APPROVED:
        logger.info("Gate 2 APPROVED for %s by %s", ticket_id, ", ".join(gate_result.approved_by))
        audit.log(
            stage=5,
            event_type="gate2_approved",
            payload={"mr_iid": mr_iid, "approved_by": gate_result.approved_by},
        )
        checkpoint.gate2_approved = True
        checkpoint.current_stage = 5

        # Update ticket to Approved / Ready to Merge
        jira.transition_ticket(
            ticket_id,
            ["Approved", "Ready to Merge", "Under Review", "In Review"],
        )
        users_str = ", ".join(f"@{u}" for u in gate_result.approved_by)
        jira.post_lifecycle_comment(
            ticket_id=ticket_id,
            title="Gate 2 Approved",
            message=f"PR was approved by {users_str}. Ready for human merge.",
            mr_url=mr_url,
        )

        notify_gate2_approved(
            slack_webhook_url=slack_webhook_url,
            escalation_email=escalation_email,
            ticket_id=ticket_id,
            mr_url=mr_url,
            approved_by=gate_result.approved_by,
        )
        notify_pipeline_complete(
            slack_webhook_url=slack_webhook_url,
            escalation_email=escalation_email,
            ticket_id=ticket_id,
            mr_url=mr_url,
        )

        return Stage5Result(
            mr_iid=mr_iid,
            mr_url=mr_url,
            status="approved",
            approved_by=gate_result.approved_by,
        )

    # ── Path B: Reviewer requested changes (FR-21) ───────────────────────
    logger.warning("Gate 2 feedback received on PR #%s: %d comment(s)", mr_iid, len(gate_result.reviewer_comments))
    audit.log(
        stage=5,
        event_type="gate2_changes_requested",
        payload={"mr_iid": mr_iid, "comments": gate_result.reviewer_comments},
    )
    gitlab.add_mr_label(mr_iid, "changes-requested")
    checkpoint.reviewer_feedback = gate_result.reviewer_comments

    jira.transition_ticket(
        ticket_id,
        ["In Progress", "Start Progress"],
    )
    comments_preview = "\n- ".join(gate_result.reviewer_comments[:3])
    jira.post_lifecycle_comment(
        ticket_id=ticket_id,
        title="Reviewer Feedback Received",
        message=(
            f"Reviewer requested changes on PR #{mr_iid}. Re-routing back to agent:\n"
            f"- {comments_preview}"
        ),
        mr_url=mr_url,
    )
    notify_feedback_received(
        slack_webhook_url=slack_webhook_url,
        escalation_email=escalation_email,
        ticket_id=ticket_id,
        mr_url=mr_url,
        feedback_notes=gate_result.reviewer_comments,
    )

    return Stage5Result(
        mr_iid=mr_iid,
        mr_url=mr_url,
        status="changes_requested",
        reviewer_feedback=gate_result.reviewer_comments,
    )

